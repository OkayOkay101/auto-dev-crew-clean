WORKFLOW_REL = ".github/workflows/ci.yml"
BRANCH_PREFIX = "ai/bootstrap-ci-"
_BRANCH_RE = re.compile(r"^[A-Za-z0-9._/-]+$")
_WRITE_PERMS = ("ADMIN", "MAINTAIN", "WRITE")
_FOOTER = "_Generated by [Claude Code](https://claude.ai/code)_"
PUSH_RETRY_WAITS = (2, 4, 8)  # seconds between attempts for transient push failures
# git push has no retry of its own; these phrases mean the network/remote hiccuped, not that the push was refused.
_TRANSIENT_PUSH = ("could not resolve", "connection", "timed out", "timeout", "rpc failed", "early eof",
                   "remote end hung up", "temporary failure", "unable to access", "network", "502", "503", "504")
_SECRET_ENV_MIN_LEN = 20
_USES_RE = re.compile(r"^(\./[^@]*|docker://\S+|[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+(/[^@]*)?@[^\s@]+)$")


@dataclass
class CiStep:
    name: str
    status: str  # ok | warn | fail | skip
    detail: str = ""


@dataclass
class CiBootstrapResult:
    status: str  # pr_opened | issue_opened | skipped | dry_run | failed
    message: str
    url: str | None = None
    steps: list[CiStep] = field(default_factory=list)
    workflow: str = ""


# ---------------------------------------------------------------- detection / generation

def has_ci_workflows(repo_dir: Path) -> bool:
    """Checks if the repository contains GitHub Actions workflow files in .github/workflows/."""
    if not repo_dir.exists() or not repo_dir.is_dir():
        return False
    wf_dir = repo_dir / ".github" / "workflows"
    if not wf_dir.exists() or not wf_dir.is_dir():
        return False
    return any(f.is_file() and f.suffix in (".yml", ".yaml") for f in wf_dir.iterdir())


def _safe_branches(base: str) -> list[str]:
    """Branch names used in the trigger filter. Anything that is not a plain ref name is dropped."""
    candidates = [base, "main", "master"]
    return list(dict.fromkeys(b for b in candidates if b and _BRANCH_RE.match(b)))


def _has_npm_test_script(repo_dir: Path) -> bool:
    try:
        data = json.loads((repo_dir / "package.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    scripts = data.get("scripts") if isinstance(data, dict) else None
    return isinstance(scripts, dict) and bool(scripts.get("test"))


def _command_lines(cmds: list[str]) -> str:
    """Join config commands into one run block. Each command may span lines; keep them as-is."""
    return "\n".join(line.rstrip() for cmd in cmds for line in cmd.splitlines()) + "\n"


def build_workflow_spec(repo_dir: Path, rcfg: dict | None = None) -> tuple[dict, list[str]]:
    """Return (workflow dict, warnings). The dict is what gets dumped to YAML."""
    rcfg = rcfg or {}
    base_branch = rcfg.get("base") or "main"
    profile = detect_stack(repo_dir)
    warnings: list[str] = []

    configured_setup = [str(s).strip() for s in (rcfg.get("setup") or []) if str(s).strip()]
    configured_test = [str(s).strip() for s in (rcfg.get("test") or []) if str(s).strip()]
    all_cmd_text = " ".join(configured_setup + configured_test).lower()

    top_files = {f.name for f in repo_dir.iterdir() if f.is_file()} if repo_dir.is_dir() else set()

    has_python_manifest = any(m in top_files for m in ("requirements.txt", "pyproject.toml", "Pipfile", "setup.py", "setup.cfg"))
    has_py_in_tests = (repo_dir / "tests").is_dir() and any((repo_dir / "tests").glob("**/*.py"))
    has_py_files = any(f.endswith(".py") for f in top_files) or has_py_in_tests
    needs_python = (
        profile.primary_language == "python"
        or has_python_manifest
        or any(k in all_cmd_text for k in ("python", "pytest", "unittest", "pip", "flake8", "ruff"))
        or has_py_files
    )

    has_node_manifest = any(m in top_files for m in ("package.json", "package-lock.json", "yarn.lock", "pnpm-lock.yaml"))
    has_js_files = any(f.endswith((".js", ".mjs", ".cjs", ".ts", ".tsx", ".jsx", ".html")) for f in top_files)
    needs_node = (
        profile.primary_language in ("javascript", "typescript")
        or has_node_manifest
        or any(k in all_cmd_text for k in ("node", "npm", "yarn", "pnpm", "bun", "npx"))
        or ("test-runner.js" in top_files)
        or has_js_files
    )
    needs_go = profile.primary_language == "go" or "go.mod" in top_files or any(k in all_cmd_text for k in ("go test", "go build"))
    needs_rust = profile.primary_language == "rust" or "Cargo.toml" in top_files or any(k in all_cmd_text for k in ("cargo test", "cargo build"))

    steps: list[dict[str, Any]] = [{"name": "Checkout repository", "uses": "actions/checkout@v4"}]

    if needs_node:
        node_step: dict[str, Any] = {"name": "Set up Node.js", "uses": "actions/setup-node@v4",
                                     "with": {"node-version": "20"}}
        if (repo_dir / "package-lock.json").exists() or (repo_dir / "npm-shrinkwrap.json").exists():
            node_step["with"]["cache"] = "npm"
        elif (repo_dir / "yarn.lock").exists():
            node_step["with"]["cache"] = "yarn"
        elif (repo_dir / "pnpm-lock.yaml").exists():
            node_step["with"]["cache"] = "pnpm"
        steps.append(node_step)

        node_setup_cmds = [s for s in configured_setup if any(k in s for k in ("npm", "yarn", "pnpm", "npx"))]
        if node_setup_cmds:
            steps.append({"name": "Install Node dependencies", "run": _command_lines(node_setup_cmds)})
        elif (repo_dir / "package-lock.json").exists():
            steps.append({"name": "Install dependencies", "run": "npm ci\n"})
        elif (repo_dir / "package.json").exists():
            steps.append({"name": "Install dependencies", "run": "npm install\n"})

    if needs_python:
        py_step: dict[str, Any] = {"name": "Set up Python", "uses": "actions/setup-python@v5",
                                   "with": {"python-version": "3.12"}}
        if (repo_dir / "requirements.txt").exists() or (repo_dir / "pyproject.toml").exists() or (repo_dir / "Pipfile").exists():
            py_step["with"]["cache"] = "pip"
        steps.append(py_step)

        py_setup_cmds = [s for s in configured_setup if any(k in s for k in ("pip", "python", "poetry", "uv"))]
        if py_setup_cmds:
            steps.append({"name": "Install Python dependencies", "run": _command_lines(py_setup_cmds)})
        elif (repo_dir / "requirements.txt").exists():
            steps.append({"name": "Install dependencies",
                          "run": "python -m pip install --upgrade pip\npip install -r requirements.txt\n"})
        elif (repo_dir / "pyproject.toml").exists():
            steps.append({"name": "Install dependencies",
                          "run": "python -m pip install --upgrade pip\npip install .[test]\n"})
        elif any("pytest" in s for s in configured_test) or (not configured_test and profile.primary_language == "python"):
            steps.append({"name": "Install dependencies",
                          "run": "python -m pip install --upgrade pip\npip install pytest\n"})

    if needs_go:
        go_step: dict[str, Any] = {"name": "Set up Go", "uses": "actions/setup-go@v5",
                                   "with": {"go-version": "stable"}}
        if (repo_dir / "go.sum").exists():
            go_step["with"]["cache"] = True
        steps.append(go_step)

    if needs_rust:
        steps.append({"name": "Set up Rust", "uses": "dtolnay/rust-toolchain@stable"})

    other_setup_cmds = [
        s for s in configured_setup
        if not any(k in s for k in ("npm", "yarn", "pnpm", "npx", "pip", "python", "poetry", "uv"))
    ]
    if other_setup_cmds:
        steps.append({"name": "Additional setup", "run": _command_lines(other_setup_cmds)})

    if configured_test:
        test_run = _command_lines(configured_test)
    elif needs_node and (repo_dir / "test-runner.js").exists():
        test_run = "node test-runner.js\n"
    elif needs_node and _has_npm_test_script(repo_dir):
        test_run = "npm test\n"
    elif needs_python:
        test_run = "pytest -q\n"
    elif needs_go:
        test_run = "go test ./...\n"
    elif needs_rust:
        test_run = "cargo test\n"
    else:
        test_run = None
        warnings.append(_i18n.t("ไม่พบคำสั่งทดสอบ — workflow จะไม่รันเทสต์จริง (ตั้งค่า test ใน config.yaml เพื่อแก้)"))
    if test_run is None:
        test_run = "echo 'No test command defined'\n"
    # pytest is the default runner for Python repos, but the install steps above only install the
    # project's own dependencies. Without pytest in those manifests the first run would fail.
    deps_text = ""
    for manifest in ("requirements.txt", "pyproject.toml", "Pipfile", "setup.cfg"):
        if (repo_dir / manifest).is_file():
            deps_text += (repo_dir / manifest).read_text(encoding="utf-8", errors="replace").lower()
    if "pytest" in test_run and needs_python and "pytest" not in deps_text and not any(
            "pytest" in s for s in configured_setup):
        steps.append({"name": "Install pytest", "run": "python -m pip install pytest\n"})
    steps.append({"name": "Run tests", "run": test_run})

    spec = {
        "name": "CI",
        "on": {
            "push": {"branches": _safe_branches(base_branch)},
            "pull_request": {"branches": _safe_branches(base_branch)},
        },
        "permissions": {"contents": "read"},
        "jobs": {"test": {"runs-on": "ubuntu-latest", "steps": steps}},
    }
    return spec, warnings


class _WorkflowDumper(yaml.SafeDumper):
    """Multi-line strings become literal blocks (``run: |``) so the file reads like hand-written YAML."""


def _represent_str(dumper: yaml.SafeDumper, data: str):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_WorkflowDumper.add_representer(str, _represent_str)


def render_workflow(spec: dict) -> str:
    text = yaml.dump(spec, Dumper=_WorkflowDumper, sort_keys=False, allow_unicode=True, width=10_000)
    # PyYAML quotes the key 'on' (a YAML 1.1 boolean); GitHub expects the plain form.
    text = re.sub(r"^'on':", "on:", text, count=1, flags=re.M)
    return text


def generate_ci_workflow_content(repo_dir: Path, repo_name: str, rcfg: dict | None = None) -> str:
    """Generates the GitHub Actions workflow YAML tailored to the repository's stack and test config."""
    spec, _ = build_workflow_spec(repo_dir, rcfg)
    return render_workflow(spec)


def validate_workflow(text: str) -> list[str]:
    """Return a list of problems; an empty list means the workflow is structurally valid."""
    try:
        doc = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        return [f"YAML ไม่ถูกต้อง: {str(exc).splitlines()[0]}"]
    if not isinstance(doc, dict):
        return ["ไฟล์ไม่ใช่ mapping ระดับบนสุด"]
    errors: list[str] = []
    if not (doc.get("on") or doc.get(True)):
        errors.append(_i18n.t("ไม่มีส่วน on (trigger)"))
    jobs = doc.get("jobs")
    if not isinstance(jobs, dict) or not jobs:
        return errors + ["ไม่มี jobs"]
    for job_name, job in jobs.items():
        if not isinstance(job, dict):
            errors.append(_i18n.t("job {p0} ไม่ใช่ mapping", p0=job_name))
            continue
        if not job.get("runs-on") or not isinstance(job.get("runs-on"), (str, list, dict)):
            errors.append(_i18n.t("job {p0} ไม่มี runs-on ที่ถูกต้อง", p0=job_name))
        steps = job.get("steps")
        if not isinstance(steps, list) or not steps:
            errors.append(_i18n.t("job {p0} ไม่มี steps", p0=job_name))
            continue
        for i, step in enumerate(steps, 1):
            if not isinstance(step, dict) or not (step.get("uses") or step.get("run")):
                errors.append(_i18n.t("job {p0} step {p1} ไม่มี uses หรือ run", p0=job_name, p1=i))
            elif step.get("uses") and not _USES_RE.match(str(step["uses"])):
                errors.append(_i18n.t("job {p0} step {p1} uses รูปแบบไม่ถูกต้อง: {p2}", p0=job_name, p1=i, p2=step['uses']))
    return errors


def actionlint_errors(text: str) -> list[str] | None:
    """Check workflow text with actionlint (schema, expressions, runner labels, shell quoting).

    Returns a list of problems (empty = clean), or None when actionlint is not installed,
    so the caller can report a skip instead of failing.
    """
    exe = shutil.which("actionlint")
    if not exe:
        return None
    try:
        res = subprocess.run([exe, "-no-color", "-"], input=text, capture_output=True, text=True,
                             encoding="utf-8", errors="replace", timeout=60)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return [f"รัน actionlint ไม่สำเร็จ: {exc}"]
    if res.returncode == 0:
        return []
    lines = [ln.strip() for ln in (res.stdout + res.stderr).splitlines() if ln.strip()]
    return lines[:10] or [f"actionlint exit {res.returncode}"]


def bootstrap_ci_workflow(repo_dir: Path, repo_name: str, rcfg: dict | None = None) -> Path | None:
    """Creates .github/workflows/ci.yml in repo_dir if no workflows exist yet.

    Returns the Path of the created file, or None if workflows already exist.
    """
    if has_ci_workflows(repo_dir):
        return None
    target = repo_dir / WORKFLOW_REL
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(generate_ci_workflow_content(repo_dir, repo_name, rcfg), encoding="utf-8")
    return target


# ---------------------------------------------------------------- process helpers

def run(cmd: list[str], cwd: Path | None = None, check: bool = True, timeout: float = 300) -> Any:
    """Helper wrapper for running process tree commands."""
    res = run_tree(
        cmd,
        cwd=cwd,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=timeout,
    )
    if check and res.returncode != 0:
        raise RuntimeError(f"Command failed ({res.returncode}): {' '.join(cmd)}\n{res.stderr}")
    return res


def gh(*args: str, check: bool = True) -> str:
    args = redact_gh_args(args)
    res = run(["gh", *args], check=check)
    return res.stdout.strip()


def clone(repo: str, base: str, branch: str, slot_id: int | None = None, depth: int = 50) -> Path:
    """Clones repo into a temporary workspace and checks out a new branch."""
    work_dir = DATA_HOME / "work"
    work_dir.mkdir(parents=True, exist_ok=True)
    prefix = f"slot-{slot_id}-{repo.split('/')[-1]}-" if slot_id is not None else f"{repo.split('/')[-1]}-"
    dest = Path(tempfile.mkdtemp(prefix=prefix, dir=work_dir))
    gh("repo", "clone", repo, str(dest), "--", "--depth", str(depth), "--branch", base)
    run(["git", "checkout", "-b", branch], cwd=dest)
    return dest


# ---------------------------------------------------------------- preflight

def _preflight_auth(repo: str) -> list[CiStep]:
    steps: list[CiStep] = []
    res = run(["gh", "auth", "status"], check=False)
    text = f"{res.stdout or ''}\n{res.stderr or ''}"
    if res.returncode != 0:
        first = next((ln.strip() for ln in text.splitlines() if ln.strip()), "gh auth status ล้มเหลว")
        steps.append(CiStep("gh login", "fail", first[:200]))
        return steps
    steps.append(CiStep("gh login", "ok"))

    scopes = re.search(r"Token scopes:\s*(.+)", text)
    if scopes:
        granted = {part.strip().strip("'\"") for part in scopes.group(1).split(",")}
        if "workflow" in granted:
            steps.append(CiStep("token scope workflow", "ok"))
        else:
            steps.append(CiStep("token scope workflow", "warn",
                                "token ไม่มี scope workflow — push ไฟล์ workflow จะถูกปฏิเสธ "
                                "ระบบจะเปิด issue แนบไฟล์ให้คนเพิ่มเองแทน"))
    else:
        steps.append(CiStep("token scope workflow", "warn",
                            "ไม่พบรายการ scope (อาจเป็น GitHub App หรือ fine-grained token) — จะลอง push จริง"))

    try:
        data = json.loads(gh("repo", "view", repo, "--json", "viewerPermission", check=False) or "{}")
        perm = str(data.get("viewerPermission") or "")
    except (ValueError, RuntimeError):
        perm = ""
    if perm in _WRITE_PERMS:
        steps.append(CiStep(_i18n.t("สิทธิ์เขียน repo"), "ok", perm))
    elif perm:
        steps.append(CiStep(_i18n.t("สิทธิ์เขียน repo"), "fail", _i18n.t("สิทธิ์ปัจจุบัน {p0} ไม่พอสำหรับ push", p0=perm)))
    else:
        steps.append(CiStep(_i18n.t("สิทธิ์เขียน repo"), "warn", _i18n.t("ตรวจสิทธิ์ไม่ได้ — จะลองทำจริง")))
    return steps


def _pr_title_body() -> tuple[str, str]:
    title = "🤖 ci: add GitHub Actions CI workflow"
    body = (
        "## 🤖 Automated CI Workflow Bootstrap\n\n"
        "Auto Dev Crew ตรวจพบว่า repository นี้ยังไม่มีระบบ Continuous Integration (CI)\n"
        "จึงสร้างไฟล์ `.github/workflows/ci.yml` ให้โดยอัตโนมัติตามโครงสร้างภาษาและชุดทดสอบของโปรเจกต์\n\n"
        "- **Stack**: GitHub Actions (`ubuntu-latest`)\n"
        "- **Triggers**: push และ pull_request บน branch หลัก\n"
        "- **Workflows**: `.github/workflows/ci.yml`\n\n"
        "---\n"
        "🤖 สร้างโดย Auto Dev Crew"
    )
    return title, body


def _open_pr(repo: str, base: str, branch: str, cfg: dict) -> str | None:
    """Open the PR. A missing label must not block the PR, so retry once without it."""
    title, body = _pr_title_body()
    common = ["pr", "create", "-R", repo, "--base", base, "--head", branch, "--title", title, "--body", body]
    label = (cfg.get("labels") or {}).get("pr")
    if label:
        try:
            return gh(*common, "--label", label)
        except RuntimeError:
            pass  # usually "label not found"; open without it
    try:
        return gh(*common)
    except RuntimeError:
        return None


def _open_fallback_issue(repo: str, content: str, reason: str, steps: list[CiStep]) -> CiBootstrapResult:
    """Last resort when the bot cannot push or open a PR: an issue holding the exact file to add by hand."""
    title = "🤖 เพิ่ม CI workflow (ระบบเปิด PR อัตโนมัติไม่ได้)"
    body = (
        "ระบบพยายามเพิ่ม CI workflow อัตโนมัติ แต่ push หรือเปิด PR ไม่สำเร็จ\n\n"
        "**วิธีเพิ่มเอง (1 นาที):** บนหน้า GitHub ให้กด *Add file → Create new file* "
        "ตั้งชื่อไฟล์เป็น `.github/workflows/ci.yml` แล้ววางเนื้อหาด้านล่าง "
        "(หน้าเว็บมีสิทธิ์ workflow ครบ จึงทำได้แม้ token ของระบบไม่มี)\n\n"
        f"```yaml\n{content}```\n\n"
        f"สาเหตุที่ระบบทำเองไม่ได้:\n```\n{reason[-600:]}\n```\n\n"
        "---\n"
        f"{_FOOTER}"
    )
    try:
        url = gh("issue", "create", "-R", repo, "--title", title, "--body", body)
    except RuntimeError as exc:
        return CiBootstrapResult("failed", _i18n.t("push/เปิด PR และเปิด issue ไม่สำเร็จ: {p0}", p0=str(exc)[-300:]),
                                 steps=steps, workflow=content)
    return CiBootstrapResult("issue_opened", _i18n.t("push/เปิด PR ไม่ได้ จึงเปิด issue ให้เพิ่มไฟล์เอง"),
                             url=url, steps=steps, workflow=content)


# ---------------------------------------------------------------- main entry points

def _is_transient_push_error(text: str) -> bool:
    lowered = text.lower()
    return any(h in lowered for h in _TRANSIENT_PUSH)


def _push_branch(cwd: Path, branch: str) -> None:
    """Push with retries for transient network errors. Non-transient errors are raised at once."""
    attempts = len(PUSH_RETRY_WAITS) + 1
    for attempt in range(1, attempts + 1):
        try:
            run(["git", "push", "-u", "origin", branch], cwd=cwd)
            return
        except RuntimeError as exc:
            if attempt == attempts or not _is_transient_push_error(str(exc)):
                raise
            time.sleep(PUSH_RETRY_WAITS[attempt - 1])


def _existing_pr_url(repo: str, branch: str) -> str | None:
    """A PR for this head branch may exist even when gh reported a failure (e.g. a timeout after
    success). Ask GitHub before deciding to delete the branch."""
    try:
        data = json.loads(gh("pr", "list", "-R", repo, "--head", branch, "--state", "all",
                             "--json", "url", check=False) or "[]")
    except ValueError:
        return None
    if isinstance(data, list) and data and isinstance(data[0], dict):
        return data[0].get("url") or None
    return None


def _contains_secret(text: str) -> bool:
    """True if the text matches a known token shape, or contains a long env secret value."""
    if redact_secrets(text) != text:
        return True
    import os
    for name, value in os.environ.items():
        if re.search(r"(KEY|TOKEN|SECRET)", name, re.I) and len(value) >= _SECRET_ENV_MIN_LEN \
                and not value.startswith("${") and value in text:
            return True
    return False


def bootstrap_ci(
    repo_name: str,
    rcfg: dict,
    cfg: dict,
    slot_id: int | None = None,
    logger: Callable[[str], None] | None = None,
    dry_run: bool = False,
) -> CiBootstrapResult:
    """Add a CI workflow to ``repo_name``. With ``dry_run=True`` only the plan is returned:
    nothing is pushed, no PR or issue is opened."""
    base_branch = rcfg.get("base") or "main"
    # random suffix: two runs in the same second must not share a branch name
    branch = f"{BRANCH_PREFIX}{dt.datetime.now():%Y%m%d-%H%M%S}-{secrets.token_hex(2)}"
    say = logger or (lambda _m: None)
    say(f"[CI-Bootstrap] {'ดราฟต์แผน' if dry_run else 'เริ่มสร้าง CI workflow'} สำหรับ {repo_name}...")

    steps: list[CiStep] = []
    cwd: Path | None = None
    try:
        steps.extend(_preflight_auth(repo_name))
        if any(s.status == "fail" for s in steps):
            return CiBootstrapResult("failed", _i18n.t("ตรวจสอบก่อนเริ่มไม่ผ่าน — ดูขั้นตอนที่ล้มเหลว"), steps=steps)

        if not _BRANCH_RE.match(base_branch):
            steps.append(CiStep(_i18n.t("สาขาฐาน"), "fail", _i18n.t("ชื่อสาขา {p0} ไม่ถูกต้อง", p0=repr(base_branch))))
            return CiBootstrapResult("failed", _i18n.t("ชื่อสาขาฐานไม่ถูกต้อง"), steps=steps)
        if not gh("api", f"repos/{repo_name}/branches/{base_branch}", "--jq", ".name", check=False):
            steps.append(CiStep(_i18n.t("สาขาฐาน"), "fail", _i18n.t("ไม่พบสาขา {p0} ใน {p1}", p0=base_branch, p1=repo_name)))
            return CiBootstrapResult("failed", _i18n.t("ไม่พบสาขาฐาน {p0}", p0=base_branch), steps=steps)
        steps.append(CiStep(_i18n.t("สาขาฐาน"), "ok", base_branch))

        # A dry run only needs the tree to detect the stack, so it clones shallowly.
        cwd = clone(repo_name, base_branch, branch, slot_id=slot_id, depth=1 if dry_run else 50)
        steps.append(CiStep(_i18n.t("clone สาขาหลัก"), "ok", base_branch))

        if has_ci_workflows(cwd):
            steps.append(CiStep(_i18n.t("ตรวจ workflow เดิม"), "skip", _i18n.t("มี workflow อยู่แล้ว")))
            return CiBootstrapResult("skipped", _i18n.t("{p0} มี workflow อยู่แล้ว ไม่ต้องเพิ่ม", p0=repo_name), steps=steps)
        steps.append(CiStep(_i18n.t("ตรวจ workflow เดิม"), "ok", _i18n.t("ยังไม่มี")))

        spec, warnings = build_workflow_spec(cwd, rcfg)
        content = render_workflow(spec)
        steps.extend(CiStep(_i18n.t("คำเตือน"), "warn", w) for w in warnings)

        errors = validate_workflow(content)
        if errors:
            steps.append(CiStep(_i18n.t("ตรวจโครงสร้าง YAML"), "fail", "; ".join(errors)))
            return CiBootstrapResult("failed", _i18n.t("workflow ที่สร้างไม่ผ่านการตรวจ"), steps=steps, workflow=content)
        steps.append(CiStep(_i18n.t("ตรวจโครงสร้าง YAML"), "ok", f"{len(spec['jobs']['test']['steps'])} steps"))

        lint = actionlint_errors(content)
        if lint is None:
            steps.append(CiStep(_i18n.t("ตรวจด้วย actionlint"), "skip", _i18n.t("ไม่ได้ติดตั้ง actionlint (ข้ามการตรวจ schema)")))
        elif lint:
            steps.append(CiStep(_i18n.t("ตรวจด้วย actionlint"), "fail", "; ".join(lint)))
            return CiBootstrapResult("failed", _i18n.t("workflow ที่สร้างไม่ผ่าน actionlint"), steps=steps, workflow=content)
        else:
            steps.append(CiStep(_i18n.t("ตรวจด้วย actionlint"), "ok"))

        if _contains_secret(content):
            steps.append(CiStep(_i18n.t("ตรวจความลับ"), "fail", _i18n.t("คำสั่งใน config มีค่าที่หน้าตาเหมือนความลับ — ไม่ commit")))
            return CiBootstrapResult("failed", _i18n.t("พบค่าที่เหมือนความลับใน workflow"), steps=steps)
        steps.append(CiStep(_i18n.t("ตรวจความลับ"), "ok"))

        if dry_run:
            steps.append(CiStep("push branch", "skip", _i18n.t("จะ push {p0} (ยังไม่ทำในโหมดดราฟต์)", p0=branch)))
            steps.append(CiStep(_i18n.t("เปิด PR"), "skip", _i18n.t("จะเปิด PR เข้า {p0}", p0=base_branch)))
            return CiBootstrapResult("dry_run", _i18n.t("แผนการเพิ่ม CI (ยังไม่ได้ push หรือเปิด PR)"),
                                     steps=steps, workflow=content)

        target = cwd / WORKFLOW_REL
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        run(["git", "add", WORKFLOW_REL], cwd=cwd)
        run(["git", "commit", "-m", "ci: add GitHub Actions workflow for automated testing"], cwd=cwd)

        try:
            _push_branch(cwd, branch)
        except RuntimeError as exc:
            reason = str(exc)
            if _is_transient_push_error(reason):
                # Network trouble is not a refusal: leave it retryable instead of opening an issue.
                steps.append(CiStep("push branch", "fail", _i18n.t("เครือข่ายขัดข้องหลังลองซ้ำแล้ว — จะลองใหม่รอบถัดไป")))
                return CiBootstrapResult("failed", _i18n.t("push ไม่สำเร็จเพราะเครือข่าย"), steps=steps, workflow=content)
            steps.append(CiStep("push branch", "fail", reason.splitlines()[-1][:200]))
            say("⚠️ [CI-Bootstrap] push ถูกปฏิเสธ — เปิด issue แนบไฟล์แทน")
            return _open_fallback_issue(repo_name, content, reason, steps)
        steps.append(CiStep("push branch", "ok", branch))

        url = _open_pr(repo_name, base_branch, branch, cfg)
        if not url:
            url = _existing_pr_url(repo_name, branch)  # the PR may exist even if gh reported failure
        if url:
            steps.append(CiStep(_i18n.t("เปิด PR"), "ok", url))
            say(f"[CI-Bootstrap] เปิด PR เพิ่ม CI ให้ {repo_name} สำเร็จ: {url} ✅")
            return CiBootstrapResult("pr_opened", _i18n.t("เปิด PR เพิ่ม CI แล้ว"), url=url, steps=steps, workflow=content)

        steps.append(CiStep(_i18n.t("เปิด PR"), "fail", _i18n.t("gh pr create ไม่สำเร็จ")))
        run(["git", "push", "origin", "--delete", branch], cwd=cwd, check=False)
        say("⚠️ [CI-Bootstrap] เปิด PR ไม่สำเร็จ — เปิด issue แนบไฟล์แทน")
        return _open_fallback_issue(repo_name, content, _i18n.t("gh pr create ไม่สำเร็จ"), steps)
    except Exception as exc:
        say(f"⚠️ [CI-Bootstrap] ไม่สามารถเพิ่ม CI ให้ {repo_name} ได้: {exc}")
        steps.append(CiStep(_i18n.t("ข้อผิดพลาด"), "fail", str(exc)[-300:]))
        return CiBootstrapResult("failed", str(exc)[-300:], steps=steps)
    finally:
        if cwd and cwd.exists():
            shutil.rmtree(cwd, ignore_errors=True)


def plan_ci_bootstrap(repo_name: str, rcfg: dict, cfg: dict, slot_id: int | None = None,
                      logger: Callable[[str], None] | None = None) -> CiBootstrapResult:
    """Draft: show every step and the generated workflow without changing anything on GitHub."""
    return bootstrap_ci(repo_name, rcfg, cfg, slot_id=slot_id, logger=logger, dry_run=True)


def create_bootstrap_ci_pr(
    repo_name: str,
    rcfg: dict,
    cfg: dict,
    slot_id: int | None = None,
    logger: Callable[[str], None] | None = None,
) -> str | None:
    """Compatibility wrapper: returns the PR (or fallback issue) URL, or None."""
    return bootstrap_ci(repo_name, rcfg, cfg, slot_id=slot_id, logger=logger).url
