"""CI bootstrap: draft, generate, validate, then open a PR (or fall back to an issue) that adds a
GitHub Actions workflow to a repository that has none.

Flow (``bootstrap_ci``):
  1. preflight  – gh login, token scope, write permission, clone of the base branch
  2. generate   – build the workflow from a dict and dump it as YAML (never string-concatenated)
  3. validate   – re-parse the YAML and check the structure; refuse content that looks like a secret
  4. dry_run?   – stop here and return the plan (nothing is pushed or opened)
  5. push       – commit to a fresh branch and push; if the push is refused (usually a token
                  without the ``workflow`` scope) fall back to an issue that carries the file
  6. open PR    – retry without the label if the label does not exist; if that also fails, fall back
                  to the issue and remove the pushed branch
"""

